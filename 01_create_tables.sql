-- Adaptive Quiz System for Children
-- Oracle Database / SQL*Plus
-- Run as a user/schema that has permission to create tables.

CREATE TABLE Student (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name VARCHAR2(100) NOT NULL,
    age NUMBER,
    class_name VARCHAR2(30),
    village_school VARCHAR2(150)
);

CREATE TABLE Subject (
    subject_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE Question (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id NUMBER NOT NULL,
    question_text VARCHAR2(500) NOT NULL,
    option_a VARCHAR2(200) NOT NULL,
    option_b VARCHAR2(200) NOT NULL,
    option_c VARCHAR2(200) NOT NULL,
    option_d VARCHAR2(200) NOT NULL,
    correct_option CHAR(1) NOT NULL,
    difficulty VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_question_subject FOREIGN KEY (subject_id)
        REFERENCES Subject(subject_id),
    CONSTRAINT chk_correct_option CHECK (correct_option IN ('A','B','C','D')),
    CONSTRAINT chk_difficulty CHECK (difficulty IN ('Easy','Medium','Hard'))
);

CREATE TABLE Quiz_Attempt (
    attempt_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    subject_id NUMBER NOT NULL,
    start_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attempt_student FOREIGN KEY (student_id)
        REFERENCES Student(student_id),
    CONSTRAINT fk_attempt_subject FOREIGN KEY (subject_id)
        REFERENCES Subject(subject_id)
);

CREATE TABLE Student_Response (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id NUMBER NOT NULL,
    question_id NUMBER NOT NULL,
    selected_option CHAR(1),
    is_correct NUMBER(1) NOT NULL,
    CONSTRAINT fk_response_attempt FOREIGN KEY (attempt_id)
        REFERENCES Quiz_Attempt(attempt_id),
    CONSTRAINT fk_response_question FOREIGN KEY (question_id)
        REFERENCES Question(question_id),
    CONSTRAINT uq_attempt_question UNIQUE (attempt_id, question_id),
    CONSTRAINT chk_selected_option CHECK (
        selected_option IS NULL OR selected_option IN ('A','B','C','D')
    ),
    CONSTRAINT chk_is_correct CHECK (is_correct IN (0,1))
);

CREATE TABLE Quiz_Result (
    result_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id NUMBER NOT NULL UNIQUE,
    total_questions NUMBER NOT NULL,
    correct_answers NUMBER NOT NULL,
    wrong_answers NUMBER NOT NULL,
    score NUMBER(5,2) NOT NULL,
    performance_level VARCHAR2(30) NOT NULL,
    CONSTRAINT fk_result_attempt FOREIGN KEY (attempt_id)
        REFERENCES Quiz_Attempt(attempt_id)
);

